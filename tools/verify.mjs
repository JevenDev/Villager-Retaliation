import { existsSync, readFileSync } from "node:fs";
import path from "node:path";
import { spawnSync } from "node:child_process";
import { fileURLToPath } from "node:url";

const repoRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const failures = [];

const syntaxFiles = [
  "tools/quest-content.mjs",
  "tools/zip-utils.js",
  "wiki/shared/search.js",
  "wiki/player/app.js",
  "wiki/player/build-data.mjs",
  "wiki/player/content/guides.js",
  "wiki/dev/app.js",
  "wiki/dev/build-data.mjs"
];

const validationScripts = [
  "tools/quest-bundle-baseline.mjs",
  "tools/test-quest-bundle-compatibility.mjs",
  "tools/validate-dialogue-data.mjs",
  "tools/test-built-in-quest-content.mjs",
  "tools/test-clipboard-tutorial-content.mjs",
  "tools/test-quest-v2-tools.mjs",
  "tools/test-quest-v3-tools.mjs",
  "tools/test-dialogue-contexts.mjs",
  "tools/test-dialogue-authoring.mjs",
  "tools/test-content-schemas.mjs",
  "tools/test-zip-utils.mjs",
  "tools/test-wiki-content.mjs"
];

const generatedChecks = [
  ["wiki/player/build-data.mjs", "--check"],
  ["wiki/dev/build-data.mjs", "--check"]
];

const requiredFiles = [
  "tools/schemas/quest-v2.schema.json",
  "tools/schemas/quest-v3.schema.json",
  "tools/schemas/quest-locale-v1.schema.json",
  "tools/schemas/quest-reward-v1.schema.json",
  "tools/schemas/scene-v1.schema.json",
  "tools/schemas/encounter-v1.schema.json",
  "tools/quest-content.mjs",
  "tools/zip-utils.js",
  "wiki/shared/search.js",
  "wiki/shared/villager_retaliation_logo.png",
  "wiki/player/index.html",
  "wiki/player/styles.css",
  "wiki/player/app.js",
  "wiki/player/content/guides.js",
  "wiki/player/site-data.js",
  "wiki/dev/index.html",
  "wiki/dev/styles.css",
  "wiki/dev/developer.css",
  "wiki/dev/app.js",
  "wiki/dev/site-data.js",
  "wiki/dev/content/Home.md",
  "wiki/dev/content/Commands.md",
  "wiki/dev/content/Tracked-Villages.md"
];

const generatedArtifacts = [
  "wiki/player/site-data.js",
  "wiki/dev/site-data.js"
];

function runNode(label, args) {
  console.log(`\n[verify] ${label}`);
  const result = spawnSync(process.execPath, args, { cwd: repoRoot, stdio: "inherit" });
  if (result.error || result.status !== 0) {
    const reason = result.error?.message
      ?? (result.signal ? `terminated by ${result.signal}` : `exit code ${result.status}`);
    failures.push(`${label}: ${reason}`);
  }
}

for (const file of requiredFiles) {
  if (!existsSync(path.join(repoRoot, file))) {
    failures.push(`Missing required file: ${file}`);
  }
}

for (const file of syntaxFiles) runNode(`syntax ${file}`, ["--check", file]);
for (const script of validationScripts) runNode(script, [script]);
for (const [script, ...args] of generatedChecks) runNode(`${script} ${args.join(" ")}`, [script, ...args]);

for (const file of generatedArtifacts) {
  if (!existsSync(path.join(repoRoot, file))) continue;
  const source = readFileSync(path.join(repoRoot, file), "utf8");
  if (!source.startsWith("// Generated by ")) {
    failures.push(`Generated artifact is missing its ownership header: ${file}`);
  }
}

if (failures.length) {
  console.error(`\n[verify] ${failures.length} checks failed:\n- ${failures.join("\n- ")}`);
  process.exitCode = 1;
} else {
  console.log("\n[verify] All repository validation passed.");
}
